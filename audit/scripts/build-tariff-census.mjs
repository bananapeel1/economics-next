#!/usr/bin/env node
// Tariff census: the command-word tables of both IAL specifications, parsed from the extracted spec
// text with a line citation on every row.
//
//   node audit/scripts/build-tariff-census.mjs            write audit/raw/tariff-census.json
//   node audit/scripts/build-tariff-census.mjs --check    exit 1 if the file on disk differs
//
// CONTENT-GATE.md, Layer 2, and its asset rule: a reference asset is GENERATED from the source text
// and spot-verified, never hand-summarised. On 12 September a hand-written summary of the Unit 2
// paper was propagated to 52 agents and was wrong. This script is the mechanism that stops that
// class of error for tariffs: lib/ial-marking.js is tested against this file, and this file carries
// the line numbers, so a disagreement is settled by reading the spec, not by arguing.
//
// Sources: IAL Economics spec Issue 2 (2018) Appendix 6, audit/raw/econ_spec.txt; IAL Business spec
// Issue 1 (2017) Appendix 6, audit/raw/bus_spec.txt.
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'audit/raw/tariff-census.json';
const CHECK = process.argv.includes('--check');

const SOURCES = [
  { subject: 'economics', file: 'audit/raw/econ_spec.txt', header: /^Appendix 6: Command word taxonomy$/m, stop: /^Appendix 7:/m },
  { subject: 'business', file: 'audit/raw/bus_spec.txt', header: /^Appendix 6: Command words$/m, stop: /^Appendix 7:/m },
];

/**
 * A table row starts with a capitalised command word at the left margin (allowing the one-space
 * indent the Economics extraction has) followed by a marks column. Continuation lines are indented
 * prose. "Evaluate/ To what extent" spans two lines in the Economics table.
 */
const ROW = /^\s{0,2}([A-Z][a-z]+(?:\/\s?To)?)\s{2,}(\d+(?:\s+or\s+\d+)?)\s{2,}(.*)$/;

function parse({ subject, file, header, stop }) {
  // The extraction carries a form feed at every page break, including on the Appendix headers.
  const text = readFileSync(file, 'utf8').replace(/\f/g, '');
  const lines = text.split('\n');
  const start = lines.findIndex((l) => header.test(l));
  if (start < 0) throw new Error(`${file}: Appendix 6 header not found`);
  const end = lines.findIndex((l, i) => i > start && stop.test(l));
  if (end < 0) throw new Error(`${file}: Appendix 7 not found after Appendix 6`);

  const rows = [];
  let current = null;
  for (let i = start + 1; i < end; i += 1) {
    const line = lines[i];
    const m = ROW.exec(line);
    if (m) {
      if (current) rows.push(current);
      let command = m[1].replace(/\/\s?To$/, '').trim(); // "Evaluate/ To" -> "Evaluate"
      const marks = m[2].split(/\s+or\s+/).map(Number);
      current = { subject, command, marks, unitNote: null, description: m[3].trim(), lines: [i + 1, i + 1] };
      continue;
    }
    if (!current) continue;
    const t = line.trim();
    if (!t) continue;
    // Page footers fall inside the table's span in the text dump; they are not part of any row.
    if (/^\d+\s+Pearson Edexcel International/.test(t) || /© Pearson Education/.test(t)) continue;
    // Business "Assess" carries a second marks value on its own line with a unit qualifier.
    const alt = /^(\d+)\s*$/.exec(t);
    if (alt && current.command === 'Assess') { current.marks.push(Number(alt[1])); current.lines[1] = i + 1; continue; }
    // "[Units 1/2]" sits mid-line beside prose in the Business table: record the tag, keep the prose.
    const unit = /\[Units? ([0-9/]+)\]/.exec(t);
    if (unit) { current.unitNote = (current.unitNote ? current.unitNote + '; ' : '') + `Units ${unit[1]}`; }
    if (/^what extent$/i.test(t)) { current.lines[1] = i + 1; continue; } // second half of "Evaluate/ To what extent"
    current.description += ' ' + t.replace(/\[Units? [0-9/]+\]/g, '').trim();
    current.lines[1] = i + 1;
  }
  if (current) rows.push(current);

  for (const r of rows) {
    r.description = r.description.replace(/\s+/g, ' ').trim();
    r.marks = [...new Set(r.marks)].sort((a, b) => a - b);
    r.source = `${file}:${r.lines[0]}-${r.lines[1]}`;
  }
  return rows;
}

const census = {
  generated: new Date().toISOString().slice(0, 10),
  note: 'Generated by audit/scripts/build-tariff-census.mjs from the extracted specification text. Do not edit by hand; regenerate. Every row cites its source lines.',
  rows: SOURCES.flatMap(parse),
};

// The parse is only worth trusting if it found the whole table.
const bySubject = (s) => census.rows.filter((r) => r.subject === s).map((r) => r.command);
const expectEcon = ['Define', 'Calculate', 'Draw', 'Explain', 'Analyse', 'Examine', 'Discuss', 'Evaluate'];
const expectBus = ['Define', 'Calculate', 'Construct', 'Explain', 'Analyse', 'Discuss', 'Assess', 'Evaluate'];
for (const [subject, expect] of [['economics', expectEcon], ['business', expectBus]]) {
  const got = bySubject(subject);
  if (got.join(',') !== expect.join(',')) {
    console.error(`${subject}: parsed ${JSON.stringify(got)}, expected ${JSON.stringify(expect)} — the table layout changed or the parser is wrong. Read the source lines.`);
    process.exit(1);
  }
}
const assess = census.rows.find((r) => r.subject === 'business' && r.command === 'Assess');
if (JSON.stringify(assess.marks) !== '[10,12]') { console.error(`business Assess parsed marks ${JSON.stringify(assess.marks)}, expected [10,12]`); process.exit(1); }

const json = JSON.stringify(census, null, 1) + '\n';
if (CHECK) {
  let onDisk = '';
  try { onDisk = readFileSync(OUT, 'utf8'); } catch { /* absent */ }
  const strip = (s) => s.replace(/"generated": "[^"]+"/, '');
  if (strip(onDisk) !== strip(json)) { console.error(`${OUT} is stale: regenerate with node audit/scripts/build-tariff-census.mjs`); process.exit(1); }
  console.log(`${OUT} matches the specification text`);
  process.exit(0);
}
writeFileSync(OUT, json);
console.log(`wrote ${OUT}: ${census.rows.length} rows`);
for (const r of census.rows) console.log(`  ${r.subject.padEnd(10)} ${r.command.padEnd(10)} ${r.marks.join(' or ').padEnd(8)} ${r.unitNote || ''}  (${r.source})`);
