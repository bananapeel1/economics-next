/* ══ LUMINA ELECTRONICS · 4.3.1 · 2a, 2b, 2c, 3c, 4b, 4c, 4d, 4e, 5b ═══════ */

export const LUMINA = (() => {
  const integratedCost = 50;
  const importedModule = 22;
  const ownAssembly = 18;
  const factoryCost = importedModule + ownAssembly;
  const freight = 2.5;
  const landed = round2(factoryCost + freight);

  const tariffRate = 20;
  const tariffPerUnit = round2(landed * tariffRate / 100);
  const landedWithTariff = round2(landed + tariffPerUnit);

  const rivalPrice = 48;
  const subsidyPerUnit = 4;
  const rivalPriceSubsidised = round2(rivalPrice - subsidyPerUnit);

  const plannedExports = 150000;
  const quotaCap = 120000;
  const blockedUnits = plannedExports - quotaCap;

  const certificationCost = 180000;
  const certificationPerUnit = round2(certificationCost / plannedExports);

  const fdi = 9000000;

  return {
    name: 'Lumina Electronics',
    integratedCost, importedModule, ownAssembly, factoryCost, freight, landed,
    tariffRate, tariffPerUnit, landedWithTariff,
    rivalPrice, subsidyPerUnit, rivalPriceSubsidised,
    plannedExports, quotaCap, blockedUnits,
    certificationCost, certificationPerUnit,
    fdi,

    /* ── derived: every one of these is a figure the section prints ───────── */
    /** 2b. What specialising saves, and as a percentage of making everything itself. */
    specialisationSaving: round2(integratedCost - factoryCost),
    specialisationSavingPct: round2((integratedCost - factoryCost) / integratedCost * 100),
    /** 2a. The share of its own cost that Lumina imports — the dependence half of 2b. */
    importedShare: round2(importedModule / factoryCost * 100),
    /** 3c. Freight priced rather than asserted. */
    freightShare: round2(freight / factoryCost * 100),
    /** 4e. Over the rival outside the bloc; under it inside. */
    gapOutside: round2(landedWithTariff - rivalPrice),
    gapInside: round2(rivalPrice - landed),
    /** 4c. The quota as a share of what the firm planned to sell. */
    blockedShare: round2((plannedExports - quotaCap) / plannedExports * 100),
    /** 4c. And what that volume was worth at the rival's price. */
    blockedRevenue: round2((plannedExports - quotaCap) * rivalPrice),
    /**
     * 4d-2. A SUBSIDY MOVES THE RIVAL'S PRICE AND NOT LUMINA'S COST, which is the row students
     * miss. Negative means Lumina is still under the rival. Inside the bloc the subsidy cuts its
     * advantage from $5.50 to $1.50; outside, on top of the tariff, it puts it $7.00 adrift.
     */
    gapAfterSubsidy: round2(landed - rivalPriceSubsidised),
    gapOutsideAfterSubsidy: round2(landedWithTariff - rivalPriceSubsidised),
    /** 2c. The parent's investment per unit of annual capacity. */
    fdiPerUnit: round2(fdi / plannedExports),
  };
})();

