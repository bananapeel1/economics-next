import { createHash } from 'node:crypto';

export const SECTION = 'globalisation';

const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
export const hash8 = (s) => createHash('sha1').update(norm(s)).digest('hex').slice(0, 8);
export const id = (kind, key) => `${SECTION}:${kind}:${hash8(key)}`;
export const subId = (s) => `${SECTION}:sub:${s}`;

export const round2 = (n) => Math.round(n * 100) / 100;

/* ── formatting: one formatter a kind of figure (packet 18) ────────────────── */

export const MINUS = '−';
export const money = (n) => `${n < 0 ? MINUS : ''}$${Number.isInteger(Math.abs(n)) ? Math.abs(n).toLocaleString('en-GB') : Math.abs(n).toFixed(2)}`;
export const qty = (n) => (Number.isInteger(n) ? n.toLocaleString('en-GB') : n.toFixed(2));
export const pct = (n) => `${Number.isInteger(n) ? n : round2(n)}%`;
/** Billions, for GDP. The unit is written every time; `quant.unit` is a DEBT rule and a habit. */
export const bn = (n) => `$${qty(n)}bn`;
/** Millions, for population. */
export const mn = (n) => `${qty(n)}m`;

/* ══ THE THREE ECONOMIES · 4.3.1 · 1a, 1b, 1c, 1d ══════════════════════════ */

/*
 * GDP PER CAPITA IS A DIVISION AND IS PERFORMED HERE, ONCE. Packet 21's rule: any figure a student
 * could compute from another must be derived from it, or the section will eventually print two of
 * them. The growth figure is a percentage CHANGE on the same population, which is QS2 and is the
 * only growth arithmetic this topic needs — nothing here compounds, and nothing here is projected.
 */
const economy = ({ key, label, gdpNow, gdpThen, population, note }) => {
  const perCapitaNow = gdpNow * 1000 / population;      // $bn → $m → per person
  const perCapitaThen = gdpThen * 1000 / population;
  return {
    key, label, population, note,
    gdpNow, gdpThen,
    perCapitaNow, perCapitaThen,
    growth: round2((gdpNow - gdpThen) / gdpThen * 100),
    perCapitaGrowth: round2((perCapitaNow - perCapitaThen) / perCapitaThen * 100),
  };
};

export const ECONOMIES = (() => {
  const rows = [
    economy({
      key: 'developed', label: 'Developed',
      gdpNow: 2400, gdpThen: 2000, population: 50,
      note: 'High income a head, most output and most jobs in services, mature markets',
    }),
    economy({
      key: 'emerging', label: 'Emerging',
      gdpNow: 400, gdpThen: 250, population: 25,
      note: 'Middle income a head, growing fast, manufacturing and services both expanding',
    }),
    economy({
      key: 'developing', label: 'Developing',
      gdpNow: 40, gdpThen: 32, population: 40,
      note: 'Low income a head, output concentrated in farming and raw materials',
    }),
  ];
  const by = Object.fromEntries(rows.map((r) => [r.key, r]));
  return {
    rows, ...by,
    /** How many times the developed economy's GDP per capita exceeds the developing one's. */
    perCapitaGap: round2(by.developed.perCapitaNow / by.developing.perCapitaNow),
    /** And the emerging one's, which is the figure `1b` is actually about. */
    emergingGap: round2(by.developed.perCapitaNow / by.emerging.perCapitaNow),
    growthRatio: round2(by.emerging.growth / by.developed.growth),
  };
})();

